import java.math.BigInteger;
import java.util.*;
import java.util.concurrent.*;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicLong;
import java.util.function.BiConsumer;

/**
 * Exact graph census for 1 <= n <= 1024. Local polynomial factors are combined
 * by intersecting their two-generator relation lattices. Equal lattices are
 * merged with their exact weights; neither words, chains, cosets, nor the
 * annihilator-divisor grid are enumerated. See docs for the partition proof.
 */
final class Census {
    private static final BigInteger ONE = BigInteger.ONE;
    private static final BigInteger TWO = BigInteger.TWO;
    private static final BigInteger THREE = BigInteger.valueOf(3);

    final int n, q, dimension;
    final BigInteger polynomial;
    final List<Factor> factors;
    final List<State> states;
    final List<Graph> graphs;
    final BigInteger stratumCount, actualChains, totalStrings, totalLoops, totalFactors;

    static final class Factor {
        final BigInteger polynomial;
        final int degree;
        final List<Local> powers;
        Factor(BigInteger polynomial, List<Local> powers) {
            this.polynomial = polynomial;
            this.degree = BinaryPolynomial.degree(polynomial);
            this.powers = List.copyOf(powers);
        }
    }

    static final class Local {
        final int exponent, period, shift;
        final BigInteger units, linkOrder, cycle;
        Local(int exponent, int period, int shift, BigInteger units,
              BigInteger linkOrder, BigInteger cycle) {
            this.exponent = exponent; this.period = period; this.shift = shift;
            this.units = units; this.linkOrder = linkOrder; this.cycle = cycle;
        }
        Relation relation() { return new Relation(period, cycle, shift); }
    }

    static final class State {
        final int period, shift;
        final BigInteger cycle, units, actualChains, strings, loops, factors;
        final String signature;
        State(Relation r, BigInteger units, BigInteger actualChains, String signature,
              BigInteger strings, BigInteger loops, BigInteger factors) {
            this.period = r.period; this.shift = r.shift; this.cycle = r.cycle;
            this.units = units; this.actualChains = actualChains;
            this.signature = signature; this.strings = strings;
            this.loops = loops; this.factors = factors;
        }
        String name() { return "G" + cycle + "-" + signature; }
    }

    static final class Graph {
        final String name, signature;
        final BigInteger cycle, loops;
        BigInteger actualChains = BigInteger.ZERO;
        BigInteger totalStrings = BigInteger.ZERO;
        BigInteger totalLoops = BigInteger.ZERO;
        BigInteger totalFactors = BigInteger.ZERO;
        Graph(State s) {
            name = s.name(); signature = s.signature; cycle = s.cycle; loops = s.loops;
        }
        void add(State s) {
            if (!cycle.equals(s.cycle) || !loops.equals(s.loops) || !signature.equals(s.signature))
                throw new IllegalStateException("Inconsistent graph shape " + name);
            actualChains = actualChains.add(s.actualChains);
            totalStrings = totalStrings.add(s.strings.multiply(s.actualChains));
            totalLoops = totalLoops.add(s.loops.multiply(s.actualChains));
            totalFactors = totalFactors.add(s.factors.multiply(s.actualChains));
        }
    }

    /** Kernel of (i,j) -> x^i (1+x)^j, generated by (d,0), (-s,t). */
    record Relation(int period, BigInteger cycle, int shift) {
        Relation {
            if (period < 1 || cycle.signum() <= 0 || shift < 0 || shift >= period)
                throw new IllegalArgumentException("Invalid relation lattice");
        }
    }
    private static final Relation TRIVIAL = new Relation(1, ONE, 0);
    private record Work(int factorIndex, int exponent, BigInteger modulus,
                        BigInteger units, BigInteger bound) { }

    Census(int n) { this(n, Math.min(32, Runtime.getRuntime().availableProcessors()), null); }

    Census(int n, int workers, BiConsumer<Long, Long> progress) {
        if (n < 1 || n > 1024) throw new IllegalArgumentException("n must be in 1..1024");
        if (workers < 1 || workers > 256)
            throw new IllegalArgumentException("workers must be in 1..256");
        this.n = n;
        q = Integer.lowestOneBit(n);
        dimension = n - q;
        BigInteger p = BigInteger.ZERO;
        for (int i = 0; i < n; i += q) p = p.setBit(i);
        polynomial = p;
        int odd = n / q;
        BigInteger squareFree = ONE.shiftLeft(odd).subtract(ONE);
        BigInteger[] irreducibles = squareFree.equals(ONE)
                ? new BigInteger[0] : BinaryPolynomial.factor(squareFree);
        Arrays.sort(irreducibles);
        BigInteger product = ONE, coreProduct = ONE;
        List<Work> work = new ArrayList<>();
        for (int i = 0; i < irreducibles.length; i++) {
            BigInteger f = irreducibles[i];
            if (i > 0 && f.equals(irreducibles[i - 1]))
                throw new IllegalStateException("Duplicate irreducible factor");
            BinaryPolynomial.verifyIrreducible(f);
            product = BinaryPolynomial.multiply(product, f);
            int degree = BinaryPolynomial.degree(f);
            BigInteger fieldOrder = ONE.shiftLeft(degree).subtract(ONE);
            BigInteger modulus = ONE;
            for (int e = 1; e <= q; e++) {
                modulus = BinaryPolynomial.multiply(modulus, f);
                BigInteger units = fieldOrder.shiftLeft(degree * (e - 1));
                BigInteger bound = fieldOrder.multiply(BigInteger.valueOf(q));
                work.add(new Work(i, e, modulus, units, bound));
            }
            coreProduct = BinaryPolynomial.multiply(coreProduct, modulus);
        }
        if (!product.equals(squareFree) || !coreProduct.equals(polynomial))
            throw new IllegalStateException("Polynomial factorization failed verification");
        stratumCount = BigInteger.valueOf(q + 1L).pow(irreducibles.length);
        Local[] measured = measureAll(work, workers, progress);
        List<Factor> localFactors = new ArrayList<>(irreducibles.length);
        for (int i = 0; i < irreducibles.length; i++) {
            List<Local> powers = new ArrayList<>(q);
            for (int e = 0; e < q; e++) powers.add(measured[i * q + e]);
            localFactors.add(new Factor(irreducibles[i], powers));
        }
        factors = List.copyOf(localFactors);

        Map<Relation, BigInteger> weights = new HashMap<>();
        weights.put(TRIVIAL, ONE);
        int accumulatedDimension = 0;
        for (Factor f : factors) {
            Map<Relation, BigInteger> next = new HashMap<>();
            // Exponent zero contributes one unit and the universal relation
            // lattice; intersecting it leaves the existing lattice unchanged.
            for (Map.Entry<Relation, BigInteger> entry : weights.entrySet()) {
                next.merge(entry.getKey(), entry.getValue(), BigInteger::add);
                for (Local local : f.powers) {
                    Relation relation = intersect(entry.getKey(), local.relation());
                    if (n % relation.period != 0)
                        throw new IllegalStateException("Rotation order does not divide n");
                    BigInteger weight = entry.getValue().multiply(local.units);
                    next.merge(relation, weight, BigInteger::add);
                }
            }
            accumulatedDimension += q * f.degree;
            BigInteger sum = BigInteger.ZERO;
            for (BigInteger weight : next.values()) sum = sum.add(weight);
            if (!sum.equals(ONE.shiftLeft(accumulatedDimension)))
                throw new IllegalStateException("Compressed relation census lost unit weights");
            weights = next;
        }
        List<Relation> relations = new ArrayList<>(weights.keySet());
        relations.sort(Comparator.comparingInt(Relation::period)
                .thenComparing(Relation::cycle).thenComparingInt(Relation::shift));
        List<State> stateList = new ArrayList<>(relations.size());
        for (Relation relation : relations) stateList.add(measureState(relation, weights.get(relation)));
        states = List.copyOf(stateList);

        Map<String, Graph> shapes = new HashMap<>();
        BigInteger count = BigInteger.ZERO, words = BigInteger.ZERO;
        BigInteger necklaces = BigInteger.ZERO, primitive = BigInteger.ZERO, core = BigInteger.ZERO;
        for (State s : states) {
            count = count.add(s.actualChains);
            core = core.add(s.units);
            words = words.add(s.strings.multiply(s.actualChains));
            necklaces = necklaces.add(s.loops.multiply(s.actualChains));
            primitive = primitive.add(s.factors.multiply(s.actualChains));
            shapes.computeIfAbsent(s.name(), ignored -> new Graph(s)).add(s);
        }
        if (!core.equals(ONE.shiftLeft(dimension)) || !words.equals(ONE.shiftLeft(n)))
            throw new IllegalStateException("Relation census does not cover the power set");
        if (!necklaces.equals(necklaceCount(n)) || !primitive.equals(primitiveCount(n)))
            throw new IllegalStateException("Independent rotation-count verification failed");
        actualChains = count;
        List<Graph> sorted = new ArrayList<>(shapes.values());
        sorted.sort(Comparator.comparing((Graph g) -> g.cycle).thenComparing(g -> g.signature));
        graphs = List.copyOf(sorted);
        totalStrings = words; totalLoops = necklaces; totalFactors = primitive;
    }

    private Local[] measureAll(List<Work> work, int requestedWorkers,
                               BiConsumer<Long, Long> progress) {
        Local[] result = new Local[work.size()];
        if (work.isEmpty()) return result;
        int workerCount = Math.min(requestedWorkers, work.size());
        AtomicInteger next = new AtomicInteger();
        AtomicLong done = new AtomicLong();
        Runnable worker = () -> {
            int i;
            while (!Thread.currentThread().isInterrupted() && (i = next.getAndIncrement()) < work.size()) {
                result[i] = measureLocal(work.get(i));
                long completed = done.incrementAndGet();
                if (progress != null) progress.accept(completed, (long)work.size());
            }
        };
        if (workerCount == 1) { worker.run(); return result; }
        ExecutorService pool = Executors.newFixedThreadPool(workerCount);
        List<Future<?>> futures = new ArrayList<>(workerCount);
        try {
            for (int i = 0; i < workerCount; i++) futures.add(pool.submit(worker));
            for (Future<?> future : futures) future.get();
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Census interrupted", e);
        } catch (ExecutionException e) {
            Throwable cause = e.getCause();
            if (cause instanceof RuntimeException r) throw r;
            if (cause instanceof Error error) throw error;
            throw new IllegalStateException("Census worker failed", cause);
        } finally {
            pool.shutdownNow();
        }
        return result;
    }

    private Local measureLocal(Work w) {
        int period = multiplicativeOrder(TWO, w.modulus, BigInteger.valueOf(n)).intValueExact();
        BigInteger linkOrder = multiplicativeOrder(THREE, w.modulus, w.bound);
        int common = linkOrder.gcd(BigInteger.valueOf(period)).intValueExact();
        BigInteger cycle = linkOrder;
        int shift = 0;
        boolean found = false;
        // The subgroup intersection has order dividing period <= n. These
        // bounded operator residues are not powerset or chain representatives.
        for (int k = common; k >= 1; k--) {
            if (common % k != 0) continue;
            BigInteger candidateCycle = linkOrder.divide(BigInteger.valueOf(k));
            BigInteger candidate = BinaryPolynomial.powMod(THREE, candidateCycle, w.modulus);
            BigInteger rotation = ONE;
            for (int i = 0; i < period; i++) {
                if (rotation.equals(candidate)) {
                    cycle = candidateCycle; shift = i; found = true; break;
                }
                rotation = BinaryPolynomial.multiplyMod(rotation, TWO, w.modulus);
            }
            if (found) break;
        }
        if (!found || !w.units.mod(cycle.multiply(BigInteger.valueOf(period))).equals(BigInteger.ZERO))
            throw new IllegalStateException("Invalid local relation lattice");
        if (!cycle.multiply(BigInteger.valueOf(period / gcd(period, shift))).equals(linkOrder))
            throw new IllegalStateException("Local relation does not reproduce the link order");
        return new Local(w.exponent, period, shift, w.units, linkOrder, cycle);
    }

    /** Exact intersection of two canonical relation lattices. */
    static Relation intersect(Relation a, Relation b) {
        BigInteger baseCycle = lcm(a.cycle, b.cycle);
        int g = gcd(a.period, b.period);
        BigInteger left = baseCycle.divide(a.cycle).multiply(BigInteger.valueOf(a.shift));
        BigInteger right = baseCycle.divide(b.cycle).multiply(BigInteger.valueOf(b.shift));
        int delta = left.subtract(right).mod(BigInteger.valueOf(g)).intValueExact();
        int multiplier = g / gcd(g, delta);
        BigInteger cycle = baseCycle.multiply(BigInteger.valueOf(multiplier));
        int period = lcm(a.period, b.period);
        int r1 = cycle.divide(a.cycle).multiply(BigInteger.valueOf(a.shift))
                .mod(BigInteger.valueOf(a.period)).intValueExact();
        int r2 = cycle.divide(b.cycle).multiply(BigInteger.valueOf(b.shift))
                .mod(BigInteger.valueOf(b.period)).intValueExact();
        // Generalized CRT. There are at most n residues to inspect because
        // both rotation orders divide n; this loop never depends on cycle size.
        for (int shift = r1; shift < period; shift += a.period)
            if (shift % b.period == r2) {
                Relation result = new Relation(period, cycle, shift);
                BigInteger orderA = a.cycle.multiply(BigInteger.valueOf(a.period / gcd(a.period, a.shift)));
                BigInteger orderB = b.cycle.multiply(BigInteger.valueOf(b.period / gcd(b.period, b.shift)));
                BigInteger resultOrder = cycle.multiply(BigInteger.valueOf(period / gcd(period, shift)));
                if (!resultOrder.equals(lcm(orderA, orderB)))
                    throw new IllegalStateException("Intersection does not reproduce the link order");
                return result;
            }
        throw new IllegalStateException("Inconsistent relation-lattice intersection");
    }

    private State measureState(Relation relation, BigInteger units) {
        int period = relation.period;
        BigInteger cycle = relation.cycle;
        BigInteger orbit = cycle.multiply(BigInteger.valueOf(period));
        BigInteger count = divideExact(units, orbit, "Nonintegral relation component count");
        int rotationTwoPart = Integer.lowestOneBit(period);
        StringBuilder sig = new StringBuilder(q + 1).append('2');
        for (int j = 1; j < q; j++)
            sig.append((j & (j - 1)) == 0 && j >= rotationTwoPart ? '1' : '2');
        sig.append('0');
        BigInteger loops = BigInteger.ZERO, fullPeriod = BigInteger.ZERO;
        for (int e = 1; e <= q; e *= 2) {
            BigInteger kernel = ONE.shiftLeft(e);
            if (e > 1) kernel = kernel.subtract(ONE.shiftLeft(e / 2));
            int liftedPeriod = lcm(period, e);
            BigInteger necklaces = divideExact(orbit.multiply(kernel), BigInteger.valueOf(liftedPeriod),
                    "Nonintegral lifted necklace count");
            loops = loops.add(necklaces);
            if (liftedPeriod == n) fullPeriod = fullPeriod.add(necklaces);
        }
        // Independently count every level of the nilpotent quotient tree and
        // verify all branching symbols against its powers-of-two orbit sizes.
        BigInteger tree = ONE, previousLevel = ONE;
        int previousRho = 1;
        for (int j = 1; j <= q; j++) {
            int rho = 1;
            while (Math.multiplyExact(rotationTwoPart, rho) < j) rho *= 2;
            BigInteger level = divideExact(ONE.shiftLeft(j - 1), BigInteger.valueOf(rho),
                    "Nonintegral tree level");
            if (j > 1) {
                int branch = 2 * previousRho / rho;
                if (sig.charAt(j - 1) - '0' != branch
                        || !previousLevel.multiply(BigInteger.valueOf(branch)).equals(level))
                    throw new IllegalStateException("Tree signature verification failed");
            }
            tree = tree.add(level);
            previousLevel = level;
            previousRho = rho;
        }
        if (!tree.multiply(cycle).equals(loops))
            throw new IllegalStateException("Tree and rotation bitloop counts differ");
        return new State(relation, units, count, sig.toString(), orbit.shiftLeft(q), loops, fullPeriod);
    }

    static BigInteger multiplicativeOrder(BigInteger value, BigInteger modulus, BigInteger bound) {
        if (modulus.equals(ONE)) return ONE;
        value = BinaryPolynomial.remainder(value, modulus);
        if (bound.signum() <= 0 || !BinaryPolynomial.powMod(value, bound, modulus).equals(ONE))
            throw new IllegalArgumentException("Invalid multiplicative-order bound");
        BigInteger order = bound;
        for (BigInteger prime : ExactInteger.primeFactors(bound))
            while (order.mod(prime).signum() == 0
                    && BinaryPolynomial.powMod(value, order.divide(prime), modulus).equals(ONE))
                order = order.divide(prime);
        return order;
    }

    /** Burnside's rotation formula, independent of the relation census. */
    static BigInteger necklaceCount(int n) {
        BigInteger sum = BigInteger.ZERO;
        for (int d = 1; d <= n; d++) if (n % d == 0)
            sum = sum.add(ONE.shiftLeft(n / d).multiply(BigInteger.valueOf(totient(d))));
        return divideExact(sum, BigInteger.valueOf(n), "Nonintegral independent necklace count");
    }

    /** Mobius inversion for rotation classes having exactly period n. */
    static BigInteger primitiveCount(int n) {
        BigInteger sum = BigInteger.ZERO;
        for (int d = 1; d <= n; d++) if (n % d == 0)
            sum = sum.add(ONE.shiftLeft(n / d).multiply(BigInteger.valueOf(mobius(d))));
        return divideExact(sum, BigInteger.valueOf(n), "Nonintegral independent primitive count");
    }

    private static BigInteger divideExact(BigInteger value, BigInteger divisor, String message) {
        BigInteger[] qr = value.divideAndRemainder(divisor);
        if (qr[1].signum() != 0) throw new IllegalStateException(message);
        return qr[0];
    }
    private static int totient(int n) {
        int result = n, rest = n;
        for (int p = 2; p <= rest / p; p++) if (rest % p == 0) {
            result -= result / p;
            do { rest /= p; } while (rest % p == 0);
        }
        if (rest > 1) result -= result / rest;
        return result;
    }
    private static int mobius(int n) {
        int result = 1, rest = n;
        for (int p = 2; p <= rest / p; p++) if (rest % p == 0) {
            rest /= p;
            if (rest % p == 0) return 0;
            result = -result;
        }
        if (rest > 1) result = -result;
        return result;
    }
    private static int gcd(int a, int b) {
        while (b != 0) { int r = a % b; a = b; b = r; }
        return a;
    }
    private static int lcm(int a, int b) { return Math.multiplyExact(a / gcd(a, b), b); }
    private static BigInteger lcm(BigInteger a, BigInteger b) { return a.divide(a.gcd(b)).multiply(b); }
}
