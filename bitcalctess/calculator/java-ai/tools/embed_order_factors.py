#!/usr/bin/env python3
"""Embed checked order data in bounded Java constants, without external resources."""
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parent.parent
raw = (root / "order-factors.json").read_bytes()
text = raw.decode("ascii")
if not text.endswith("\n") or "\\" in text or '"""' in text:
    raise ValueError("Factor data must have a final newline and no text-block escapes")
# Java constant-pool UTF-8 entries are limited to 65535 bytes. Keep independent
# text blocks well below that bound and join at runtime, avoiding constant folding.
chunks, chunk = [], ""
for line in text.splitlines(keepends=True):
    if len(line) > 24000:
        raise ValueError("Factor-data line is too long for a Java constant")
    if len(chunk) + len(line) > 24000:
        chunks.append(chunk)
        chunk = ""
    chunk += line
if chunk:
    chunks.append(chunk)
source = (
    "// Generated by tools/embed_order_factors.py; edit order-factors.json instead.\n"
    "// SHA-256: " + hashlib.sha256(raw).hexdigest() + "\n"
    "final class OrderFactorData {\n"
    "    private OrderFactorData() { }\n"
    '    static final String JSON = String.join("",\n'
    + ',\n'.join('"""\n' + part + '"""' for part in chunks)
    + ");\n}\n"
)
(root / "OrderFactorData.java").write_text(source, encoding="utf-8")
