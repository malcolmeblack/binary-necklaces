"""Exact graph census by weighted intersections of two-generator lattices.

The algorithm factors x**m+1, where n=m*2**a and m is odd. It never lists
binary words, necklaces, components, or component representatives. Difficult
integer orders or too many distinct lattices produce an explicit resource
limit, rather than an unproved period or an incomplete count labeled exact.
"""
from math import gcd, lcm

try:
    from . import finitefield as ff
    from .numbertheory import ComputationLimit, MAX_INTEGER_BITS, factor_integer, divisors, totient, mobius
except ImportError:
    import finitefield as ff
    from numbertheory import ComputationLimit, MAX_INTEGER_BITS, factor_integer, divisors, totient, mobius


TRIVIAL = (1, 1, 0)


def power_set_totals(n):
    if not isinstance(n, int) or isinstance(n, bool) or not 1 <= n <= 4096:
        raise ValueError("n must be an integer in 1..4096")
    ds = divisors(n)
    return {
        "n": n,
        "words": 1 << n,
        "necklaces": sum(totient(d) * (1 << (n // d)) for d in ds) // n,
        "primitive_necklaces": sum(mobius(d) * (1 << (n // d)) for d in ds) // n,
    }


def _divide_exact(a, b):
    q, r = divmod(a, b)
    if r:
        raise ArithmeticError("Nonintegral algebraic count")
    return q


def _order(value, modulus, bound, check, integer_cache):
    if modulus == 1:
        return 1
    if bound.bit_length() > MAX_INTEGER_BITS:
        raise ComputationLimit(f"The required integer order bound exceeds the {MAX_INTEGER_BITS}-bit factoring limit")
    if ff.pow_mod(value, bound, modulus, check) != 1:
        raise ArithmeticError("Invalid multiplicative-order bound")
    if bound not in integer_cache:
        integer_cache[bound] = factor_integer(bound, check)
    order = bound
    for prime in integer_cache[bound]:
        while order % prime == 0 and ff.pow_mod(value, order // prime, modulus, check) == 1:
            order //= prime
    return order


def _base_relation(f, n, check, integer_cache):
    """Kernel of (i,j) -> x**i*(1+x)**j in a binary finite field."""
    if check:
        check()
    odd = n // (n & -n)
    period = _order(2, f, odd, check, integer_cache)
    link_order = _order(3, f, (1 << ff.degree(f)) - 1, check, integer_cache)
    rotations, rotation = {}, 1
    for shift in range(period):
        if check:
            check()
        rotations[rotation] = shift
        rotation = ff.multiply_mod(rotation, 2, f)
    for intersection_size in reversed(divisors(gcd(period, link_order))):
        cycle = link_order // intersection_size
        candidate = ff.pow_mod(3, cycle, f, check)
        if candidate in rotations:
            shift = rotations[candidate]
            if cycle * (period // gcd(period, shift)) != link_order:
                raise ArithmeticError("Local relation does not reproduce the word period")
            return period, cycle, shift
    raise ArithmeticError("No local relation found")


def intersect(a, b):
    """Intersect lattices generated by (d,0) and (-s,t)."""
    da, ta, sa = a
    db, tb, sb = b
    base = lcm(ta, tb)
    g = gcd(da, db)
    delta = ((base // ta) * sa - (base // tb) * sb) % g
    cycle = base * (g // gcd(g, delta))
    period = lcm(da, db)
    r1, r2 = (cycle // ta * sa) % da, (cycle // tb * sb) % db
    # Generalized CRT, without a search through the (possibly long) cycle.
    reduced = db // g
    k = 0 if reduced == 1 else (((r2 - r1) // g) * pow(da // g, -1, reduced)) % reduced
    shift = (r1 + da * k) % period
    if cycle * (period // gcd(period, shift)) != lcm(ta * (da // gcd(da, sa)), tb * (db // gcd(db, sb))):
        raise ArithmeticError("Inconsistent relation-lattice intersection")
    return period, cycle, shift


def _lift_relation(base, exponent):
    # For f != x,x+1 irreducible, the f-adic order of x**i*(1+x)**j+1
    # is a power of two: after dividing i,j by their common two-power,
    # its derivative is nonzero at a root of f. Therefore the relation
    # lattice modulo f**e is 2**ceil(log2(e)) times the field lattice.
    scale = 1 << (exponent - 1).bit_length()
    return tuple(scale * value for value in base)


def relation_for_modulus(H, n, check=None):
    """Return (rotation period, necklace cycle length, shift) for a unit stratum.

    H must divide x**n+1 and be coprime to x and x+1. The necklace period t
    satisfies (1+x)**t=x**s mod H; the literal word period is t*d/gcd(d,s).
    """
    if not isinstance(n, int) or not 1 <= n <= 4096:
        raise ValueError("n must be in 1..4096")
    if H < 1 or ff.gcd(H, 6) != 1:
        raise ValueError("The modulus must be coprime to x and x+1")
    if ff.remainder((1 << n) | 1, H):
        raise ValueError("The modulus must divide x**n+1")
    relation, integer_cache = TRIVIAL, {}
    for f, exponent in ff.factor_with_multiplicity(H, check).items():
        if check:
            check()
        local = _lift_relation(_base_relation(f, n, check, integer_cache), exponent)
        relation = intersect(relation, local)
    d, t, s = relation
    if ff.pow_mod(2, d, H, check) != ff.remainder(1, H) or ff.pow_mod(3, t, H, check) != ff.pow_mod(2, s, H, check):
        raise ArithmeticError("Final relation verification failed")
    return relation


def graph_shape(n, relation):
    """Component shape and mass for a nonzero-support relation lattice."""
    q = n & -n
    d, cycle, _ = relation
    rotation_two_part = d & -d
    sequence = "2" + "".join("1" if j & (j - 1) == 0 and j >= rotation_two_part else "2" for j in range(1, q)) + "0"
    orbit = d * cycle
    loops, primitive = 0, 0
    e = 1
    while e <= q:
        kernel = (1 << e) - ((1 << (e // 2)) if e > 1 else 0)
        lifted = lcm(d, e)
        necklaces = _divide_exact(orbit * kernel, lifted)
        loops += necklaces
        if lifted == n:
            primitive += necklaces
        e *= 2
    # Independent tree-level calculation checks the branching sequence.
    tree, previous_level, previous_rho = 1, 1, 1
    for j in range(1, q + 1):
        rho = 1
        while rotation_two_part * rho < j:
            rho *= 2
        level = _divide_exact(1 << (j - 1), rho)
        if j > 1 and (int(sequence[j - 1]) != 2 * previous_rho // rho or previous_level * int(sequence[j - 1]) != level):
            raise ArithmeticError("Branching sequence verification failed")
        tree += level
        previous_level, previous_rho = level, rho
    if tree * cycle != loops:
        raise ArithmeticError("Tree and rotation necklace counts differ")
    return {
        "name": "G%d-%s" % (cycle, sequence),
        "cycle_length": cycle,
        "branching_sequence": sequence,
        "depth": q,
        "necklaces": loops,
        "words": orbit << q,
        "primitive_necklaces": primitive,
    }


def _graph_row_bytes(row):
    """Conservative compact-JSON size, including quoted decimal integers.

    These rows contain only nonnegative integers and ASCII names/sequences,
    with no characters requiring JSON escaping. Quoting every value also
    covers the HTTP adapter's conversion of large integers to decimal strings.
    This measures one row, never serializing or copying the full catalogue.
    """
    return 2 + max(0, len(row) - 1) + sum(
        len(key) + 3 + len(str(value)) + 2 for key, value in row.items())


def census(n, check=None, max_states=10000, max_graphs=None, max_graph_bytes=None):
    """Return exact totals with a complete graph table when it fits the limits.

    Every graph row counts actual weakly connected components, without pairing
    components under reversal or selecting a minimum representative.
    Optional output limits bound table retention during aggregation, while
    keeping exact counts and coverage checks. A limit produces ``summary_only``
    and ``graphs=None``, never a partial table. Defaults retain the full table.
    Computation limits and deadlines still raise; they do not yield partial
    totals presented as a completed summary.
    """
    totals = power_set_totals(n)
    if isinstance(max_states, bool) or not isinstance(max_states, int) or max_states < 1:
        raise ValueError("max_states must be a positive integer")
    for name, limit in (("max_graphs", max_graphs), ("max_graph_bytes", max_graph_bytes)):
        if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int) or limit < 1):
            raise ValueError(f"{name} must be a positive integer or None")
    q, integer_cache = n & -n, {}
    odd = n // q
    # (x**odd+1)/(x+1) is 1+x+...+x**(odd-1), squarefree for odd odd.
    factors = ff.factor_squarefree((1 << odd) - 1, check)
    weights = {TRIVIAL: 1}
    accumulated_dimension = 0
    for f in factors:
        if check:
            check()
        degree = ff.degree(f)
        base = _base_relation(f, n, check, integer_cache)
        choices = [(TRIVIAL, 1)]
        # Exponents e in (r/2,r] have the same relation. Sum their unit
        # weights geometrically instead of enumerating q exponent choices.
        previous, r = 0, 1
        while r <= q:
            weight = (1 << (degree * r)) - (1 << (degree * previous))
            choices.append((_lift_relation(base, r), weight))
            previous, r = r, r * 2
        following = {}
        for old, weight in weights.items():
            if check:
                check()
            for local, local_weight in choices:
                relation = intersect(old, local)
                if n % relation[0]:
                    raise ArithmeticError("Rotation period does not divide n")
                following[relation] = following.get(relation, 0) + weight * local_weight
                if len(following) > max_states:
                    raise ComputationLimit("The graph census exceeded its distinct-lattice limit")
        accumulated_dimension += q * degree
        if sum(following.values()) != 1 << accumulated_dimension:
            raise ArithmeticError("Compressed census lost unit weights")
        weights = following
    graphs, identities, graph_bytes, table_limit_reason = {}, set(), 2, None
    words, necklaces, primitive, components = 0, 0, 0, 0
    for relation, weight in sorted(weights.items()):
        if check:
            check()
        d, t, _ = relation
        count = _divide_exact(weight, d * t)
        shape = graph_shape(n, relation)
        # For fixed n, the two-part of d determines the branching sequence;
        # together with the cycle length it determines exactly the graph name.
        # Keep these small identities even after discarding a large table.
        identity = (d & -d, t)
        identities.add(identity)
        if graphs is not None:
            if max_graphs is not None and len(identities) > max_graphs:
                graphs = None
                table_limit_reason = f"The complete graph table exceeds the {max_graphs}-row output limit."
            else:
                old = graphs.get(identity)
                if old is None:
                    graph = {key: value for key, value in shape.items() if key not in ("words", "primitive_necklaces")}
                    graph.update(components=0, total_words=0, total_necklaces=0, total_primitive_necklaces=0)
                    old_bytes = 0
                else:
                    if old["necklaces"] != shape["necklaces"]:
                        raise ArithmeticError("Inconsistent graph shape")
                    graph, old_bytes = old.copy(), _graph_row_bytes(old)
                graph["components"] += count
                graph["total_words"] += shape["words"] * count
                graph["total_necklaces"] += shape["necklaces"] * count
                graph["total_primitive_necklaces"] += shape["primitive_necklaces"] * count
                # Include the list delimiters and commas. Check the candidate
                # before retaining it; duplicate updates may add decimal digits.
                proposed_bytes = graph_bytes + _graph_row_bytes(graph) - old_bytes
                if old is None and graphs:
                    proposed_bytes += 1
                if max_graph_bytes is not None and proposed_bytes > max_graph_bytes:
                    graphs = None
                    table_limit_reason = f"The complete graph table exceeds the {max_graph_bytes}-byte output limit."
                else:
                    graphs[identity] = graph
                    graph_bytes = proposed_bytes
        components += count
        words += shape["words"] * count
        necklaces += shape["necklaces"] * count
        primitive += shape["primitive_necklaces"] * count
    if check:
        check()
    verification = {
        "word_partition": words == totals["words"],
        "necklace_partition": necklaces == totals["necklaces"],
        "primitive_partition": primitive == totals["primitive_necklaces"],
    }
    if not all(verification.values()):
        raise ArithmeticError("Independent power-set accounting failed")
    graph_rows = None if graphs is None else sorted(graphs.values(), key=lambda g: (g["cycle_length"], g["branching_sequence"]))
    if check:
        check()
    result = {
        "status": "summary_only" if graphs is None else "exact", **totals, "components": components,
        "graph_types": len(identities),
        "graphs": graph_rows,
        "graphs_returned": 0 if graph_rows is None else len(graph_rows),
        "graphs_truncated": graphs is None,
        "verification": verification,
        "relation_states": len(weights),
        "component_convention": "actual weakly connected components; no reversal pairing",
    }
    if table_limit_reason is not None:
        result["reason"] = table_limit_reason
    return result
